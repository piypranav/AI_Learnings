num1 = int(input("Enter first number: "))
num2 = int(input("Enter second number: "))
num3 = int(input("Enter third number: "))

subtract = num1 - num2 - num3
print("The result of subtraction is:", subtract)

add = num1 + num2 + num3
print("The result of addition is:", add)

multiply = num1 * num2 * num3
print("The result of multiplication is:", multiply)

divide = num1 / num2
divide = divide / num3
print("The result of division is:", divide)

reminder = num1 % num2
print("The result of reminder is:", reminder)

quotient = num1 // num2
print("The result of quotient is:", quotient)
